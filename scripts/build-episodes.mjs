// Renders the episode rows into the static pages from one source of truth.
//
// content/episodes.json is the canonical slate. This script writes the rows
// between the EPISODES:START / EPISODES:END markers in:
//   public/index.html            featured only (01 to 10)
//   public/episodes.html         the full slate (01 to 30)
//
// The site has no build step by design, so this is run by hand after editing
// the data, the same way scripts/generate-favicons.mjs is:
//
//   node scripts/build-episodes.mjs
//
// Run it and commit the resulting HTML. Never hand-edit rows between the
// markers, they will be overwritten.

import { readFile, writeFile } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

const START = '<!-- EPISODES:START (generated by scripts/build-episodes.mjs, do not edit by hand) -->';
const END = '<!-- EPISODES:END -->';

function escapeText(value) {
  return String(value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;');
}

// titleHtml carries an intentional <em> for the italic secondary-phrase
// pattern, so only the text around that tag is escaped.
function titleMarkup(titleHtml) {
  return titleHtml
    .split(/(<\/?em>)/)
    .map((part) => (part === '<em>' || part === '</em>' ? part : escapeText(part)))
    .join('');
}

function renderRow(ep, indent, heading) {
  const pad = ' '.repeat(indent);
  const subtitle = ep.subtitle
    ? `\n${pad}    <p class="tx-subtitle">${escapeText(ep.subtitle)}</p>`
    : '';
  return [
    `${pad}<article class="tx-row">`,
    `${pad}  <div class="tx-num">${escapeText(ep.number)}</div>`,
    `${pad}  <div class="tx-main">`,
    `${pad}    <${heading} class="tx-title">${titleMarkup(ep.titleHtml)}</${heading}>${subtitle}`,
    `${pad}    <p class="tx-desc">${escapeText(ep.description)}</p>`,
    `${pad}  </div>`,
    `${pad}  <p class="tx-question">${escapeText(ep.question)}</p>`,
    `${pad}</article>`,
  ].join('\n');
}

// heading: the archive lists episodes directly under the page h1, so they are
// h2 there. On the homepage they sit inside a section that already has an h2.
async function inject(file, episodes, indent, heading) {
  const path = resolve(root, file);
  const html = await readFile(path, 'utf8');
  const start = html.indexOf(START);
  const end = html.indexOf(END);
  if (start === -1 || end === -1) {
    throw new Error(`markers not found in ${file}`);
  }
  const pad = ' '.repeat(indent);
  const rows = episodes.map((ep) => renderRow(ep, indent, heading)).join('\n');
  const next =
    html.slice(0, start + START.length) + '\n' + rows + '\n' + pad + html.slice(end);
  await writeFile(path, next, 'utf8');
  return episodes.length;
}

const episodes = JSON.parse(await readFile(resolve(root, 'content/episodes.json'), 'utf8'));

// No em dashes in rendered copy. Enforced here so a data edit cannot
// reintroduce one without the build failing.
const offenders = episodes.filter((ep) =>
  Object.values(ep).some((v) => typeof v === 'string' && v.includes('—'))
);
if (offenders.length) {
  throw new Error(`em dash in episodes: ${offenders.map((e) => e.number).join(', ')}`);
}

const featured = episodes.filter((ep) => ep.featured);
console.log(`index.html    ${await inject('public/index.html', featured, 4, 'h3')} rows`);
console.log(`episodes.html ${await inject('public/episodes.html', episodes, 4, 'h2')} rows`);
