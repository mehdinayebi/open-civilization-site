// Renders the public episode rows into the homepage from one source of truth.
//
// content/episodes.json holds the full internal editorial slate. Only the
// records marked featured, currently 01 to 10, are ever rendered publicly.
// Records 11 and up stay in the file as editorial planning and must not reach
// a public page, a public count, or a public link.
//
// There is no public archive page. The rows are written between the
// EPISODES:START / EPISODES:END markers in public/index.html only.
//
// The site has no build step at deploy time, so this is run by hand after
// editing the data, the same way scripts/generate-favicons.mjs is:
//
//   node scripts/build-episodes.mjs
//
// Run it and commit the resulting HTML. Never hand-edit rows between the
// markers, they will be overwritten.

import { readFile, writeFile } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

const TARGET = 'public/index.html';
const START = '<!-- EPISODES:START (generated by scripts/build-episodes.mjs, do not edit by hand) -->';
const END = '<!-- EPISODES:END -->';
const INDENT = 4;

// The public row carries a number, a title, a summary and a governing question.
// Nothing else. Subtitles were removed from the public system deliberately.
const ALLOWED_FIELDS = new Set([
  'number',
  'title',
  'titleHtml',
  'description',
  'question',
  'slug',
  'featured',
]);

function escapeText(value) {
  return String(value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;');
}

// titleHtml carries an intentional <em> for the italic secondary-phrase
// pattern, so only the text around that tag is escaped.
function titleMarkup(titleHtml) {
  return titleHtml
    .split(/(<\/?em>)/)
    .map((part) => (part === '<em>' || part === '</em>' ? part : escapeText(part)))
    .join('');
}

// h3: the rows sit inside the Episodes section, which already carries the h2.
function renderRow(ep) {
  const pad = ' '.repeat(INDENT);
  return [
    `${pad}<article class="tx-row">`,
    `${pad}  <div class="tx-num">${escapeText(ep.number)}</div>`,
    `${pad}  <div class="tx-main">`,
    `${pad}    <h3 class="tx-title">${titleMarkup(ep.titleHtml)}</h3>`,
    `${pad}    <p class="tx-desc">${escapeText(ep.description)}</p>`,
    `${pad}  </div>`,
    `${pad}  <p class="tx-question">${escapeText(ep.question)}</p>`,
    `${pad}</article>`,
  ].join('\n');
}

const episodes = JSON.parse(await readFile(resolve(root, 'content/episodes.json'), 'utf8'));

// ── validation ───────────────────────────────────────────────────────────────

// Numbering must be a contiguous zero-padded sequence from 01.
episodes.forEach((ep, i) => {
  const expected = String(i + 1).padStart(2, '0');
  if (ep.number !== expected) {
    throw new Error(`episode numbering breaks at index ${i}: got ${ep.number}, expected ${expected}`);
  }
});

// A subtitle field must not come back: it would render nowhere and silently
// diverge from the public design.
const withSubtitle = episodes.filter((ep) => 'subtitle' in ep);
if (withSubtitle.length) {
  throw new Error(
    `subtitle is not part of the public episode system, found on: ${withSubtitle
      .map((e) => e.number)
      .join(', ')}`
  );
}

// Fail loudly on an unknown field rather than dropping it without a word.
for (const ep of episodes) {
  const unknown = Object.keys(ep).filter((k) => !ALLOWED_FIELDS.has(k));
  if (unknown.length) {
    throw new Error(`episode ${ep.number} has unrecognised field(s): ${unknown.join(', ')}`);
  }
}

// No em dashes in rendered copy. Enforced here so a data edit cannot
// reintroduce one without the build failing.
const emDash = episodes.filter((ep) =>
  Object.values(ep).some((v) => typeof v === 'string' && v.includes('—'))
);
if (emDash.length) {
  throw new Error(`em dash in episodes: ${emDash.map((e) => e.number).join(', ')}`);
}

const featured = episodes.filter((ep) => ep.featured);
if (featured.length < 10) {
  throw new Error(`expected at least 10 featured episodes, found ${featured.length}`);
}

// ── render ───────────────────────────────────────────────────────────────────

const path = resolve(root, TARGET);
const html = await readFile(path, 'utf8');
const start = html.indexOf(START);
const end = html.indexOf(END);
if (start === -1 || end === -1) {
  throw new Error(`markers not found in ${TARGET}`);
}

const rows = featured.map(renderRow).join('\n');
const next =
  html.slice(0, start + START.length) + '\n' + rows + '\n' + ' '.repeat(INDENT) + html.slice(end);
await writeFile(path, next, 'utf8');

console.log(`${TARGET}  ${featured.length} rows rendered, ${episodes.length - featured.length} held back internally`);
